Result<void> UnicodeScripts::pre_tokenize(PreTokenizedString& pretokenized) const {
    return pretokenized.split([](size_t, NormalizedString normalized) -> Result<std::vector<NormalizedString>> {
        std::string_view text = normalized.get();
        if (text.empty()) return std::vector<NormalizedString>{};

        std::optional<Script> last_script;
        size_t pos = 0;
        std::vector<size_t> split_points;

        while (pos < text.size()) {
            size_t char_start = pos;
            char32_t c = decode_utf8(text, pos);
            Script script = fixed_script(c);

            if (script != Script::Any
                && last_script.has_value() && *last_script != Script::Any
                && *last_script != script) {
                split_points.push_back(char_start);
            }
            if (script != Script::Any) {
                last_script = script;
            }
        }

        if (split_points.empty()) {
            std::vector<NormalizedString> result;
            result.push_back(std::move(normalized));
            return result;
        }

        split_points.push_back(text.size());
        std::vector<NormalizedString> result;
        size_t start = 0;
        for (size_t end : split_points) {
            if (end > start) {
                auto sl = normalized.slice(Range::normalized(start, end));
                if (sl) result.push_back(std::move(*sl));
            }
            start = end;
        }
        // Last segment
        if (start < text.size()) {
            auto sl = normalized.slice(Range::normalized(start, text.size()));
            if (sl) result.push_back(std::move(*sl));
        }
        return result;
    });
}

