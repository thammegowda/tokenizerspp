Script get_script(char32_t c) noexcept {
    const auto it = std::lower_bound(
        SCRIPT_RANGES.begin(), SCRIPT_RANGES.end(), c,
        [](const ScriptRange& range, char32_t cp) { return range.last < cp; });
    if (it != SCRIPT_RANGES.end() && c >= it->first) {
        return it->script;
    }
    return Script::Any;
}

// Remap Hiragana/Katakana to Han, U+30FC to Han, space to Any
Script fixed_script(char32_t c) noexcept {
    if (c == U' ') return Script::Any;
    if (c < 0x80) {
        if ((c >= U'A' && c <= U'Z') || (c >= U'a' && c <= U'z')) return Script::Latin;
        return Script::Common;
    }
    if (c == 0x30FC) return Script::Han;
    const Script s = get_script(c);
    if (s == Script::Hiragana || s == Script::Katakana) return Script::Han;
    return s;
}

// Decode next UTF-8 codepoint from pos, advance pos
char32_t decode_utf8(std::string_view s, size_t& pos) noexcept {
    auto b0 = static_cast<unsigned char>(s[pos]);
    if (b0 < 0x80) { pos += 1; return b0; }
    char32_t cp;
    size_t len;
    if ((b0 & 0xE0) == 0xC0) { cp = b0 & 0x1F; len = 2; }
    else if ((b0 & 0xF0) == 0xE0) { cp = b0 & 0x0F; len = 3; }
    else { cp = b0 & 0x07; len = 4; }
    for (size_t i = 1; i < len && pos + i < s.size(); ++i)
        cp = (cp << 6) | (static_cast<unsigned char>(s[pos + i]) & 0x3F);
    pos += len;
    return cp;
}

